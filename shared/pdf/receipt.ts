import { rgb } from "pdf-lib";
import type { ReceiptModel } from "./models.ts";
import { drawQr } from "./qr.ts";
import { METHOD, MUTED, Writer, dateLong, inr, monthLong, newDoc } from "./writer.ts";

/** A5 rent receipt. Voided payments keep their receipt; it renders with a VOID notice. */
export async function renderReceipt(m: ReceiptModel): Promise<Uint8Array> {
  const { doc, font, bold } = await newDoc(`Rent receipt ${m.number}`);
  const w = new Writer(doc, font, bold, [419.53, 595.28]); // A5
  w.brand("Rent receipt", m.number, `Issued ${dateLong(m.issuedOn)}`);

  if (m.voided) {
    w.text("VOID", { size: 18, bold: true, color: rgb(0.8, 0.1, 0.1) });
    w.lineDone(18, 1.3);
    const when = m.voidedOn ? dateLong(m.voidedOn) : "";
    w.para(
      `This payment was voided by the landlord${when ? ` on ${when}` : ""}${m.voidReason ? `: ${m.voidReason}` : ""}. It no longer counts toward the rent.`,
      { size: 9, color: MUTED, after: 8 },
    );
  }
  w.text("Amount received", { size: 9, color: MUTED });
  w.lineDone(9, 1.6);
  w.text(inr(m.amount), { size: 24, bold: true });
  w.lineDone(24, 1.25);
  w.para(m.amountWords, { size: 9, color: MUTED, after: 8 });

  w.pair("Received from", m.tenantName, { bold: true });
  const lines = m.lines ?? [];
  w.pair(
    "For",
    lines.length > 1 && m.monthTo
      ? `Rent for ${monthLong(m.month)} to ${monthLong(m.monthTo)} (${lines.length} months)`
      : `Rent for ${monthLong(m.month)}`,
  );
  w.pair("Property", `${m.unitLabel}, ${m.propertyName}`);
  if (m.address) w.pair("Address", m.address);
  w.pair("Paid on", dateLong(m.paidOn));
  w.pair("Paid by", `${METHOD[m.method] ?? m.method}${m.utr ? ` · Ref ${m.utr}` : ""}`);
  if (m.note) w.pair("Note", m.note);
  w.rule();
  if (lines.length) {
    // Multi-month payment: what went to each month, then the month's remaining balance.
    w.text("Month-wise breakdown", { size: 9, color: MUTED });
    w.lineDone(9, 1.6);
    for (const l of lines) {
      const of =
        l.extra > 0 ? ` of ${inr(l.chargeAmount)} (incl. ${inr(l.extra)} utilities)` : ` of ${inr(l.chargeAmount)}`;
      w.pair(monthLong(l.month), `${inr(l.applied)}${of}${l.balance ? ` · ${inr(l.balance)} left` : " · paid"}`);
    }
    w.rule();
    w.pair("Total received", inr(m.amount), { bold: true });
    w.pair("Balance on these months", m.balance ? inr(m.balance) : "Nil · paid in full", { bold: true });
  } else {
    if (m.extra > 0) {
      w.pair("Rent", inr(m.chargeAmount - m.extra));
      w.pair("Utilities (meter)", inr(m.extra));
    }
    w.pair(`Total for ${monthLong(m.month)}`, inr(m.chargeAmount));
    w.pair("Paid so far", inr(m.paidTotal));
    w.pair("Balance", m.balance ? inr(m.balance) : "Nil · paid in full", { bold: true });
  }
  w.rule();
  w.para("Received with thanks.", { size: 10, after: 18 });
  w.text(m.ownerName || "Landlord", { bold: true });
  w.lineDone(10);
  w.text(`Landlord${m.ownerPhone ? ` · ${m.ownerPhone}` : ""}${m.ownerUpi ? ` · UPI ${m.ownerUpi}` : ""}`, {
    size: 8.5,
    color: MUTED,
  });
  w.lineDone(8.5);
  if (m.verifyUrl) {
    // Anyone holding the paper can scan this to see that pOS issued it, and whether it was later voided.
    const size = 58;
    w.gap(12);
    w.ensure(size + 4);
    const top = w.y;
    drawQr(w, m.verifyUrl, w.m, top, size);
    w.y = top - 14;
    w.text("Scan to verify this receipt", { size: 9, bold: true, x: size + 12 });
    w.lineDone(9, 1.5);
    w.text("Shows the amount, the date and whether it is still valid.", { size: 8, color: MUTED, x: size + 12 });
    w.y = top - size - 4;
  }
  w.footer("Generated by pOS from the rent ledger. A computer-generated receipt.");
  return doc.save();
}
